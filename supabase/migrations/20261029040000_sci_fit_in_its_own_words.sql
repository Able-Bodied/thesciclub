update public.organizations set description = $bio$SCI-FIT gives activity-based therapy to people living with paralysis, for those "looking to go above and beyond traditional therapy." Its mission: "to provide the most comprehensive activity based therapy for individuals living with paralysis."

- For spinal cord injury, stroke and other neurological conditions, including multiple sclerosis, traumatic brain injury, cerebral palsy and transverse myelitis
- A program tailored to each person: range of motion, load bearing, gait training, balance, strength and functional electrical stimulation (FES)
- **Equipment:** Lokomat robotic walking, Amadeo finger and hand therapy, and RT300 FES bikes for arms and legs
- Physical therapy with a licensed physical therapist at the Dublin center
- Training for family and caregivers, to keep the program going at home
- Six centers: Dublin, Sacramento, Fresno, Petaluma, Modesto (in Salida) and Chandler, Arizona

Dan Dumas and Annabelle Constantin opened the first center, in Pleasanton, in 2007, so people with spinal cord injuries could take part in an intensive program without having to move.

To start, apply to the nearest center and a team member sets up a free evaluation. Clients need a doctor's clearance for intense exercise and weight bearing, and to breathe on their own.

